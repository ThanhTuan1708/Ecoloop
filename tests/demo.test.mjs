import { test } from 'node:test';
import assert from 'node:assert/strict';
import { initialDemo, submitDemo, approveDemo, redeemDemo } from '../src/model.ts';
test('demo follows pending → approval → redemption, guards duplicate actions and evidence', () => {
  const hash = '0x' + '1'.repeat(64);
  const initial = initialDemo();
  const submitted = submitDemo(initial, 0, 5000, hash);
  assert.equal(submitted.balance, initial.balance);
  assert.throws(() => submitDemo(submitted, 0, 5000, hash), /Ảnh này/);
  const approved = approveDemo(submitted, 5, 4000);
  assert.equal(approved.balance, initial.balance + 80);
  assert.equal(approved.totalGrams, initial.totalGrams + 4000);
  assert.throws(() => approveDemo(approved, 5, 4000), /đã được xử lý/);
  const redeemed = redeemDemo(approved, 1);
  assert.equal(redeemed.balance, initial.balance - 20);
  assert.equal(redeemed.rewards[0].stock, initial.rewards[0].stock - 1);
  assert.equal(redeemed.redemptions.length, 2);
  assert.throws(() => redeemDemo({ ...initial, balance: 0 }, 1), /chưa đủ/);
  assert.throws(() => submitDemo({ ...initial, paused: true }, 0, 5000, hash), /tạm dừng/);
  assert.throws(() => approveDemo({ ...submitted, paused: true }, 5, 4000), /tạm dừng/);
});
