// Generates src/theme-dark.css from the light stylesheets (web.css, pickup.css).
// Every light surface/border becomes a dark one and every dark text colour becomes a light one,
// keeping the original hue, so brand colours (green, orange) stay recognisable.
// Re-run after editing web.css or pickup.css:  node scripts/gen-dark-theme.mjs
import fs from 'node:fs';
import path from 'node:path';

const src = path.resolve(import.meta.dirname, '../src');
const inputs = ['web.css', 'pickup.css', 'mobile.css', 'onchain.css'];
const PREFIX = ':root[data-theme=dark]';

const NAMED = { white: '#ffffff', black: '#000000' };
function parse(token) {
  const t = NAMED[token.toLowerCase()] || token;
  let m = /^#([0-9a-f]{3,8})$/i.exec(t);
  if (m) {
    let h = m[1];
    if (h.length === 3 || h.length === 4) h = [...h].map(c => c + c).join('');
    const n = [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16) / 255);
    const a = h.length === 8 ? parseInt(h.slice(6, 8), 16) / 255 : 1;
    return [...n, a];
  }
  m = /^rgba?\(([^)]+)\)$/i.exec(t);
  if (m) {
    const p = m[1].split(/[\s,/]+/).filter(Boolean).map(Number);
    return [p[0] / 255, p[1] / 255, p[2] / 255, p[3] ?? 1];
  }
  return null;
}
function toHsl([r, g, b]) {
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h * 60, s, l];
}
function fmt(h, s, l, a) {
  const c = v => Math.round(Math.min(1, Math.max(0, v)) * 1000) / 10;
  return a < 1 ? `hsl(${Math.round(h)} ${c(s)}% ${c(l)}% / ${Math.round(a * 100) / 100})` : `hsl(${Math.round(h)} ${c(s)}% ${c(l)}%)`;
}
// kind: 'bg' surfaces, 'line' borders/outlines, 'text' foreground
function convert(token, kind) {
  const rgba = parse(token);
  if (!rgba) return token;
  const [h, s, l] = toHsl(rgba), a = rgba[3];
  if (kind === 'text') return l < 0.5 ? fmt(h, s * 0.8, 0.9 - l * 0.55, a) : token;
  // vivid accents (brand orange, red badges…) keep their colour
  const light = l > 0.55 && !(s > 0.6 && l < 0.75);
  if (kind === 'line') return light ? fmt(h, s * 0.45, 0.2 + (1 - l) * 0.4, a) : token;
  return light ? fmt(h, s * 0.55, 0.105 + (1 - l) * 0.4, a) : token;
}
const COLOR = /#[0-9a-f]{3,8}\b|rgba?\([^)]*\)|\b(?:white|black)\b/gi;
function kindOf(prop) {
  if (/^(background|background-color|background-image)$/.test(prop)) return 'bg';
  if (/^(border|border-(top|right|bottom|left)(-color)?|border-color)$/.test(prop)) return 'line';
  if (/^(color|fill|stroke|caret-color|text-decoration-color)$/.test(prop)) return 'text';
  return null;
}
function transformDecls(body) {
  const out = [];
  for (const decl of body.split(';')) {
    const i = decl.indexOf(':');
    if (i < 0) continue;
    const prop = decl.slice(0, i).trim().toLowerCase(), value = decl.slice(i + 1).trim();
    const kind = kindOf(prop);
    if (!kind) continue;
    // black text/background with alpha is usually a shadow-like overlay; keep it
    const next = value.replace(COLOR, t => (/^black$/i.test(t) && kind === 'bg') ? t : convert(t, kind));
    // Re-emit unchanged colours too, so the prefixed rules keep the original cascade order
    // (e.g. an active-state rule still wins over the base rule).
    out.push(`${prop}:${next}`);
  }
  return out.join(';');
}
function prefix(selectors) {
  // `:root[data-layout=mobile] .x` → `:root[data-theme=dark][data-layout=mobile] .x`
  return selectors.split(',').map(s => s.trim()).filter(Boolean)
    .map(s => s.startsWith(':root[') ? PREFIX + s.slice(5) : `${PREFIX} ${s}`).join(',');
}
// Minimal CSS walker: handles flat rules and one level of @media / @supports.
function walk(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  let out = '', i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    const head = css.slice(i, open).trim();
    if (head.startsWith('@media') || head.startsWith('@supports')) {
      let depth = 1, j = open + 1;
      while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
      const inner = walk(css.slice(open + 1, j - 1));
      if (inner) out += `${head}{${inner}}\n`;
      i = j;
      continue;
    }
    const close = css.indexOf('}', open);
    if (head.startsWith('@')) { // @keyframes etc.: skip the whole block
      let depth = 1, j = open + 1;
      while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
      i = j;
      continue;
    }
    const decls = transformDecls(css.slice(open + 1, close));
    if (decls) out += `${prefix(head)}{${decls}}\n`;
    i = close + 1;
  }
  return out;
}

let result = `/* Generated by scripts/gen-dark-theme.mjs from ${inputs.join(', ')}. Do not edit by hand. */\n`;
for (const file of inputs) result += `/* ${file} */\n` + walk(fs.readFileSync(path.join(src, file), 'utf8'));
fs.writeFileSync(path.join(src, 'theme-dark.css'), result);
console.log(`Wrote src/theme-dark.css (${result.split('\n').length} rules)`);
